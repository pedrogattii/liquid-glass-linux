import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = async file => (await readFile(new URL('../extensions/blur-my-shell@aunetx/'+file,import.meta.url),'utf8')).replace(/^import .*;\n/gm,'');
const managerSource=await source('pipelines/effects_manager.js');
const EffectsManager=new Function('get_internal_effects','get_supported_effects',managerSource.replace('export const EffectsManager =','return '))(()=>({}),()=>({blur:{class:class {}}}));
const manager=new EffectsManager({});
const order=[];
const effect={_bms_manager_type:'blur',get_actor:()=>({remove_effect:()=>order.push('effect')})};
manager.used.add(effect);
const surface={destroy(){assert.ok(manager.used.has(effect));order.push('surface');manager.dynamicSurfaces.delete(this);}};
manager.dynamicSurfaces.add(surface);
manager.destroy_all();
assert.deepEqual(order,['surface','effect']);
assert.equal(manager.dynamicSurfaces.size,0);
assert.equal(manager.used.size,0);
assert.deepEqual(manager.blur_effects,[]);
const pipelineSource=await source('render/dynamic_surface.js');
const DynamicPipeline=new Function(pipelineSource.replace('export class DynamicPipeline','return class DynamicPipeline'))();
const pipeline=new DynamicPipeline(manager,{},'test');
assert.ok(manager.dynamicSurfaces.has(pipeline));
pipeline.destroy();
assert.equal(manager.dynamicSurfaces.size,0);
pipeline.destroy();
assert.equal(manager.dynamicSurfaces.size,0);
console.log('blur surfaces: registered ownership, pre-manager detachment and idempotent disposal passed');
